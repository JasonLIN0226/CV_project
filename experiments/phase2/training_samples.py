"""Offline predictor samples with causal histories and explicit memory dropout.

This adapter consumes already encoded, provenance-checked trajectories. It does
not fit normalization/bases, encode images, train a model, or load checkpoints.
Random subsets are an offline training augmentation, not a deployable eviction
policy. Streaming modes use the common irreversible memory implementation.

The causal input object has past/current observations and executed actions only.
Future targets and recorded continuations live in a separate OfflineFuture.
The explicit legacy bridge joins the continuation into WORLD-MODEL inputs; that
dictionary must never be passed to an online retention scorer.
"""

from __future__ import annotations

from dataclasses import dataclass
import hashlib
import json
from types import MappingProxyType
from typing import Mapping, Sequence

import numpy as np

from .deletion import OfflineFuture
from .memory import MemoryEntry, POLICIES, StreamingMemory, StreamingSnapshot


INDEPENDENT_POLICIES = ("fifo", "reservoir", "temporal_buckets", "visual_diversity")
DEFAULT_MODES = ("random_fixed", "random_subset") + INDEPENDENT_POLICIES
SUPPORTED_MODES = ("recent_only", "random_fixed", "random_subset") + POLICIES
ACTION_SEMANTICS = ("additive_controls", "absolute_targets", "ordered_controls")


def _integer(value, name, minimum=0):
    if isinstance(value, (bool, np.bool_)) or not isinstance(value, (int, np.integer)) or value < minimum:
        raise ValueError(f"{name} must be an integer >= {minimum}")
    return int(value)


def _text(value, name):
    if not isinstance(value, str) or not value.strip():
        raise ValueError(f"{name} must be a nonempty string")
    return value


def _immutable(array):
    a = np.ascontiguousarray(array)
    return np.frombuffer(a.tobytes(), dtype=a.dtype).reshape(a.shape)


def _matrix(array, name):
    a = np.asarray(array)
    if a.ndim != 2 or a.shape[1] == 0 or a.dtype not in (np.dtype("float32"), np.dtype("float64")):
        raise ValueError(f"{name} must be a 2-D float32/float64 array with a nonempty last dimension")
    if not np.isfinite(a).all():
        raise ValueError(f"{name} must be finite")
    return _immutable(a)


@dataclass(frozen=True)
class EpisodeIdentity:
    episode_id: str
    group_id: str
    split: str
    task: str
    environment_seed: int
    dynamics_id: str | None = None

    def __post_init__(self):
        for name in ("episode_id", "group_id", "split", "task"):
            _text(getattr(self, name), name)
        object.__setattr__(self, "environment_seed", _integer(self.environment_seed, "environment_seed"))
        if self.dynamics_id is not None:
            _text(self.dynamics_id, "dynamics_id")

    @classmethod
    def from_record(cls, record: Mapping, *, dynamics_id: str | None = None):
        """Read only identity keys from the original observation-index schema.

        `pair` groups both siblings and all derived samples/forks. No evaluation
        file, state, evidence timestamp, gap, or class field is read here.
        """
        return cls(record["id"], record["pair"], record["split"], record["task"], record["seed"], dynamics_id)


class SplitRegistry:
    """Validate declared trajectory/group/seed splits before any sampling.

    Environment seeds are scoped by task; repeating the same task/seed across
    splits is rejected even under different group IDs. Optional dynamics_split
    maps selected dynamics IDs to their sole declared split. This is validation
    of supplied metadata, not proof that an array was generated by that seed.
    Historical test_* data default to development_evaluation, never untouched.
    """

    def __init__(self, records: Sequence[EpisodeIdentity], *,
                 dynamics_split: Mapping[str, str] | None = None,
                 split_roles: Mapping[str, str] | None = None):
        records = tuple(records)
        if not records or any(not isinstance(r, EpisodeIdentity) for r in records):
            raise ValueError("records must be nonempty EpisodeIdentity values")
        assignments = dict(dynamics_split or {})
        for key, value in assignments.items():
            _text(key, "dynamics ID")
            _text(value, "dynamics split")
        episodes, groups, seeds = {}, {}, {}
        for record in records:
            if record.episode_id in episodes:
                raise ValueError("duplicate episode ID in split registry")
            episodes[record.episode_id] = record
            for table, key, name in ((groups, record.group_id, "group"),
                                      (seeds, (record.task, record.environment_seed), "environment seed")):
                previous = table.setdefault(key, record.split)
                if previous != record.split:
                    raise ValueError(f"{name} appears in more than one split")
            if record.dynamics_id in assignments and record.split != assignments[record.dynamics_id]:
                raise ValueError("selected dynamics setting violates its declared split")
        roles = dict(split_roles or {})
        known_splits = {r.split for r in records}
        if not set(roles) <= known_splits:
            raise ValueError("split role declared for an unknown split")
        for split in known_splits:
            roles.setdefault(split, "training" if split == "train" else "validation" if split == "validation" else "development_evaluation")
            _text(roles[split], "split role")
        self.records = MappingProxyType(episodes)
        self.roles = MappingProxyType(roles)
        self.dynamics_split = MappingProxyType(assignments)

    def require(self, identity: EpisodeIdentity, expected_split: str):
        _text(expected_split, "expected_split")
        if self.records.get(identity.episode_id) != identity:
            raise ValueError("episode identity is missing from or differs from the split registry")
        if identity.split != expected_split:
            raise ValueError(f"sample requires split {expected_split!r}, not {identity.split!r}")


@dataclass(frozen=True, eq=False)
class FeatureEpisode:
    """One complete offline trajectory; observations use contiguous times 0..T-1.

    action[t] is the control applied after observing frame t to obtain frame
    t+1. feature_space_id must identify the encoder, preprocessing and train-only
    normalization used by the caller; a supplied name alone is not verification.
    Raw image/hidden simulator state fields deliberately do not exist here.
    """

    identity: EpisodeIdentity
    features: np.ndarray
    actions: np.ndarray
    action_semantics: str
    feature_space_id: str

    def __post_init__(self):
        if not isinstance(self.identity, EpisodeIdentity):
            raise ValueError("identity must be an EpisodeIdentity")
        features, actions = _matrix(self.features, "features"), _matrix(self.actions, "actions")
        if not len(features) or len(actions) != len(features) - 1:
            raise ValueError("T observations require exactly T-1 aligned actions")
        if self.action_semantics not in ACTION_SEMANTICS:
            raise ValueError(f"action_semantics must be one of {ACTION_SEMANTICS}")
        _text(self.feature_space_id, "feature_space_id")
        object.__setattr__(self, "features", features)
        object.__setattr__(self, "actions", actions)


@dataclass(frozen=True)
class SamplingConfig:
    recent_length: int = 4
    capacity: int = 2
    horizons: tuple[int, ...] = (3, 6)
    history_modes: tuple[str, ...] = DEFAULT_MODES
    memory_dropout: float = 0.15
    temporal_bucket_width: int = 8

    def __post_init__(self):
        for name in ("recent_length", "capacity", "temporal_bucket_width"):
            object.__setattr__(self, name, _integer(getattr(self, name), name, 1))
        horizons = tuple(_integer(h, "horizon", 1) for h in self.horizons)
        if not horizons or list(horizons) != sorted(set(horizons)):
            raise ValueError("horizons must be nonempty, distinct and ordered")
        modes = tuple(self.history_modes)
        if not modes or len(set(modes)) != len(modes) or any(m not in SUPPORTED_MODES for m in modes):
            raise ValueError("history_modes must be distinct supported mode names")
        probability = float(self.memory_dropout)
        if not np.isfinite(probability) or not 0 <= probability <= 1:
            raise ValueError("memory_dropout must be a probability in [0,1]")
        object.__setattr__(self, "horizons", horizons)
        object.__setattr__(self, "history_modes", modes)
        object.__setattr__(self, "memory_dropout", probability)


@dataclass(frozen=True, eq=False)
class PredictorContext:
    """Causal inputs only. Offline action history is not a bounded runtime cache."""

    current_time: int
    recent: tuple[MemoryEntry, ...]
    history: tuple[MemoryEntry, ...]
    executed_actions: np.ndarray
    action_semantics: str


@dataclass(frozen=True, eq=False)
class PredictorSample:
    causal: PredictorContext
    future: OfflineFuture
    metadata: Mapping


@dataclass(frozen=True)
class SuppliedHistory:
    """A caller-produced streaming result, with its policy identity explicit.

    This adapter verifies the supplied values/timestamps against observed data,
    but cannot establish that a caller's attention/surprise implementation was
    causal. Audit that implementation before using it for scientific training.
    """

    policy: str
    snapshot: StreamingSnapshot

    def __post_init__(self):
        if self.policy not in POLICIES or not isinstance(self.snapshot, StreamingSnapshot):
            raise ValueError("SuppliedHistory requires a named policy and StreamingSnapshot")


def _seed(base_seed: int, identity: EpisodeIdentity, query: int, epoch: int, draw: int, purpose: str) -> int:
    # Exclude sibling episode ID: paired siblings share random choices/dropout.
    parts = [base_seed, identity.task, identity.group_id, query, epoch, draw, purpose]
    return int.from_bytes(hashlib.sha256(json.dumps(parts, separators=(",", ":")).encode()).digest()[:8], "little")


def _observed_entry(episode: FeatureEpisode, timestamp: int) -> MemoryEntry:
    return MemoryEntry(episode.identity.episode_id, timestamp, episode.features[timestamp])


def _provided_indices(episode: FeatureEpisode, query: int, config: SamplingConfig,
                      supplied: SuppliedHistory) -> np.ndarray:
    snapshot = supplied.snapshot
    expected_recent = tuple(range(query - config.recent_length + 1, query + 1))
    if snapshot.current_time != query or snapshot.observations_seen != query + 1 or tuple(e.timestamp for e in snapshot.recent) != expected_recent:
        raise ValueError("supplied streaming snapshot does not match this query/recent window")
    if len(snapshot.retained) != min(config.capacity, expected_recent[0]):
        raise ValueError("supplied history must match the capacity/warm-up count")
    times = tuple(e.timestamp for e in snapshot.retained)
    if list(times) != sorted(set(times)) or any(t >= expected_recent[0] for t in times):
        raise ValueError("supplied history must be distinct, ordered, and precede recent")
    for item in snapshot.recent + snapshot.retained:
        if item.episode_id != episode.identity.episode_id or item.representation.dtype != episode.features.dtype or not np.array_equal(item.representation, episode.features[item.timestamp]):
            raise ValueError("supplied streaming entry differs from this episode's observed feature")
    return np.asarray(times, dtype=np.int64)


def sample_predictor(episode: FeatureEpisode, registry: SplitRegistry,
                     config: SamplingConfig, *, query: int, base_seed: int,
                     epoch: int = 0, draw: int = 0, expected_split: str = "train",
                     history_mode: str | None = None,
                     supplied_history: SuppliedHistory | None = None) -> PredictorSample:
    """Produce one reproducible offline predictor example.

    The default mixture is uniform across declared modes. Random subsets sample
    only timestamps before the recent boundary. `random_subset` draws a count
    uniformly from 0..min(K, available_history), then samples without replacement.
    Dropout independently discards all historical entries with configured p;
    recent observations, targets and actions are unchanged. Evaluation splits
    force dropout off and require epoch=draw=0 for fixed validation sampling.

    Each query is a separately seeded prefix replay, not continuation of a prior
    query's reservoir. Use a persistent StreamingMemory for online evaluation;
    adjacent calls here are independent offline examples and may select an
    observation absent from another example's history.

    Attention/surprise histories require an explicitly supplied audited streaming
    snapshot. No unavailable model-dependent policy is silently replaced by FIFO.
    """
    if not isinstance(episode, FeatureEpisode) or not isinstance(registry, SplitRegistry) or not isinstance(config, SamplingConfig):
        raise ValueError("explicit FeatureEpisode, SplitRegistry and SamplingConfig required")
    registry.require(episode.identity, expected_split)
    query = _integer(query, "query")
    base_seed, epoch, draw = (_integer(v, n) for v, n in ((base_seed, "base_seed"), (epoch, "epoch"), (draw, "draw")))
    if query >= len(episode.features) or query < config.recent_length - 1:
        raise ValueError("query must have a complete recent buffer within this trajectory")
    if expected_split != "train" and (epoch != 0 or draw != 0):
        raise ValueError("evaluation sampling requires fixed epoch=draw=0")
    if history_mode is not None and history_mode not in SUPPORTED_MODES:
        raise ValueError("unsupported history mode")
    mode_rng = np.random.default_rng(_seed(base_seed, episode.identity, query, epoch, draw, "mode"))
    mode = history_mode or config.history_modes[int(mode_rng.integers(len(config.history_modes)))]
    stop = query - config.recent_length + 1
    subset_rng = np.random.default_rng(_seed(base_seed, episode.identity, query, epoch, draw, "subset"))
    stream_seed = _seed(base_seed, episode.identity, query, epoch, draw, "stream")
    if supplied_history is not None:
        if not isinstance(supplied_history, SuppliedHistory) or supplied_history.policy != mode:
            raise ValueError("supplied history policy must match the explicitly selected mode")
        indices = _provided_indices(episode, query, config, supplied_history)
        source = "supplied_streaming_snapshot_requires_external_policy_audit"
    elif mode == "recent_only":
        indices = np.empty(0, np.int64)
        source = "recent_only"
    elif mode in ("random_fixed", "random_subset"):
        count = min(config.capacity, stop)
        if mode == "random_subset":
            count = int(subset_rng.integers(count + 1))
        indices = np.sort(subset_rng.choice(stop, count, replace=False)).astype(np.int64)
        source = "offline_causal_subset_augmentation"
    elif mode in INDEPENDENT_POLICIES:
        stream = StreamingMemory(config.recent_length, config.capacity, mode,
                                 seed=stream_seed, temporal_bucket_width=config.temporal_bucket_width)
        for timestamp in range(query + 1):
            snapshot = stream.push(_observed_entry(episode, timestamp))
        indices = np.array([e.timestamp for e in snapshot.retained], dtype=np.int64)
        source = "common_irreversible_streaming_replay"
    else:
        raise ValueError(f"{mode} needs a supplied audited model-dependent streaming snapshot")
    before_dropout = tuple(map(int, indices))
    probability = config.memory_dropout if expected_split == "train" else 0.0
    dropout_rng = np.random.default_rng(_seed(base_seed, episode.identity, query, epoch, draw, "dropout"))
    dropout_event = bool(dropout_rng.random() < probability)
    if dropout_event:
        indices = np.empty(0, np.int64)
    recent = tuple(_observed_entry(episode, t) for t in range(stop, query + 1))
    history = tuple(_observed_entry(episode, int(t)) for t in indices)
    # Separate allocations prevent .base from reaching later action suffixes.
    causal = PredictorContext(query, recent, history, _immutable(episode.actions[:query]), episode.action_semantics)
    available = np.array([query + h < len(episode.features) for h in config.horizons], dtype=bool)
    if not available.any():
        raise ValueError("query has no available future prediction target")
    targets = np.full((len(config.horizons), episode.features.shape[1]), np.nan, dtype=episode.features.dtype)
    for index, horizon in enumerate(config.horizons):
        if available[index]:
            targets[index] = episode.features[query + horizon]
    future = OfflineFuture(config.horizons, targets,
                           _immutable(episode.actions[query:query + max(config.horizons)]), available)
    metadata = MappingProxyType({
        "episode_id": episode.identity.episode_id, "group_id": episode.identity.group_id,
        "split": episode.identity.split, "split_role": registry.roles[episode.identity.split],
        "task": episode.identity.task, "environment_seed": episode.identity.environment_seed,
        "dynamics_id": episode.identity.dynamics_id, "feature_space_id": episode.feature_space_id,
        "base_seed": base_seed, "epoch": epoch, "draw": draw, "query": query,
        "mode": mode, "history_source": source, "capacity": config.capacity,
        "history_before_dropout": before_dropout, "history_after_dropout": tuple(map(int, indices)),
        "dropout_probability": probability, "dropout_event": dropout_event,
        "dropout_removed_entries": len(before_dropout) if dropout_event else 0,
        "stream_seed": stream_seed if mode in INDEPENDENT_POLICIES and supplied_history is None else None,
    })
    return PredictorSample(causal, future, metadata)


def phase1_arrays(sample: PredictorSample) -> tuple[dict[str, np.ndarray], np.ndarray]:
    """Explicit bridge to phase1.inputs.collate for Gate/Motion world models.

    This does not load or validate any model. The caller must establish matching
    feature normalization/basis/checkpoint identity. It refuses absolute PushT
    controls: summing absolute targets is not the inherited additive convention.
    Recorded future controls are WORLD-MODEL conditioning only, never retention
    inputs. Target features remain outside the returned model-input dictionary.
    """
    if not isinstance(sample, PredictorSample):
        raise ValueError("sample must be a PredictorSample")
    causal, future = sample.causal, sample.future
    if causal.action_semantics != "additive_controls" or causal.executed_actions.shape[1] != 2:
        raise ValueError("legacy phase1 bridge requires two-dimensional additive_controls")
    if len(causal.recent) != 4 or future.horizons != (3, 6):
        raise ValueError("legacy phase1 bridge requires recent=4 and horizons=(3,6)")
    if not future.available.all():
        raise ValueError("legacy phase1 predictor cannot consume missing target horizons")
    entries = causal.recent + causal.history
    if entries[0].representation.dtype != np.dtype("float32") or causal.executed_actions.dtype != np.dtype("float32") or future.actions.dtype != np.dtype("float32"):
        raise ValueError("legacy phase1 bridge requires float32 features and actions")
    times = np.array([e.timestamp for e in entries], np.int64)
    prefix = np.concatenate([np.zeros((1, 2), np.float32), np.cumsum(causal.executed_actions, axis=0)])
    arrays = {
        "z": np.stack([e.representation for e in entries]),
        "age": (causal.current_time - times).astype(np.float32),
        "type": np.r_[np.zeros(len(causal.recent), np.int64), np.ones(len(causal.history), np.int64)],
        "past_actions": prefix[causal.current_time] - prefix[times],
        "actions": future.actions, "current": causal.recent[-1].representation,
    }
    return {key: _immutable(value) for key, value in arrays.items()}, _immutable(future.targets)
