"""Turn the reproduction manifest into Slurm job arrays for one run.

    python torch/make_jobs.py --run-id <id> --select gate.replay gate.retrain_scorer

Run this locally. It writes torch/generated/<run_id>/ (one task list and one sbatch file per
selected task, plus submit.sh) and runs/<run_id>/run.json, which Mutagen syncs to the cluster.
The generated files hold no account and no path: submit.sh reads them on the cluster from
torch/cluster.sh (environment variables, or your own torch/.env). Then submit from the cluster
with plain sbatch calls, no Python on the login node:

    ssh torch 'bash /scratch/$USER/CV_project/torch/generated/<run_id>/submit.sh'

Every seed and variant listed in configs/reproduction.yaml becomes one array index, so none can be
left out. submit.sh copies src/, scripts/, configs/ and torch/ into the run's scratch folder first
and the jobs run from that copy (pytest tasks run from the checkout), so later edits to the checkout cannot change a queued job.
`--select` takes task-id prefixes.
"""
from __future__ import annotations

import argparse
import hashlib
import itertools
import json
import subprocess
import sys
import time
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
REPO = HERE.parent
SBATCH = """#!/bin/bash
#SBATCH --job-name={job}
#SBATCH --cpus-per-task={cpus}
#SBATCH --mem={mem}
#SBATCH --time={time}
#SBATCH --array=0-{last}{throttle}
{gres}# Generated by torch/make_jobs.py from configs/reproduction.yaml for run {run_id}, task {task}. Do not edit.
# Submit through torch/generated/{run_id}/submit.sh, which supplies the account, the log file and
# the settings of torch/cluster.sh (BM_SCRATCH, BM_REPO, HF_HOME, the conda environment).
set -euo pipefail
: "${{BM_CODE:?submit through submit.sh}}" "${{BM_SCRATCH:?}}" "${{BM_RUN:?}}" "${{BM_OUT:?}}" "${{BM_REPO:?}}" "${{HF_HOME:?}}" "${{BM_CONDA_SH:?}}" "${{BM_CONDA_ENV:?}}"
export OMP_NUM_THREADS=$SLURM_CPUS_PER_TASK MKL_NUM_THREADS=$SLURM_CPUS_PER_TASK TOKENIZERS_PARALLELISM=false PYTHONUNBUFFERED=1
source "$BM_CONDA_SH"
conda activate "$BM_CONDA_ENV"
{env}mapfile -t TASKS < "$BM_CODE/torch/generated/{run_id}/{task}.tasks"
cd "{cwd}"
LINE="${{TASKS[$SLURM_ARRAY_TASK_ID]}}"
echo "== $(hostname) $(date -Is) {task}[$SLURM_ARRAY_TASK_ID]: $LINE"
eval "python $LINE"
echo "BM_TASK_DONE {task}[$SLURM_ARRAY_TASK_ID] $(date -Is)"
"""


def commands(task_id, task):
    """One command line per (variant, seed); the order fixes the array index."""
    base = task["script"]
    if task.get("config"):
        base += f" --config {task['config']}"
    extra = task.get("args", "")
    variants = task.get("variants") or {}
    keys = list(variants)
    lines = []
    for combo in itertools.product(*(variants[k] for k in keys)):
        flags = "".join(f" --{k} {v}" for k, v in zip(keys, combo))
        if task.get("seeds") is None:
            lines.append(f"{base}{flags} {extra}".rstrip())
            continue
        for seed in task["seeds"]:
            line = f"{base} --seed {seed} --device {task.get('device', 'cpu')}{flags}"
            if "--out " not in extra:
                line += f" --out ${{BM_OUT}}/{task['out']}"
            lines.append(f"{line} {extra}".rstrip())
    if not lines:
        raise ValueError(f"{task_id}: expands to no command")
    return lines


def git(*args):
    return subprocess.run(["git", "-C", str(REPO), *args], capture_output=True, text=True, check=True).stdout


def code_state():
    digest = hashlib.sha256()
    files = sorted(p for d in ("src", "scripts", "configs") for p in (REPO / d).rglob("*") if p.is_file()
                   and "__pycache__" not in p.parts)
    for path in files:
        digest.update(str(path.relative_to(REPO)).encode()); digest.update(path.read_bytes())
    return {"git_head": git("rev-parse", "HEAD").strip(), "git_branch": git("branch", "--show-current").strip(),
            "tracked_files_modified": [l[3:] for l in git("status", "--porcelain").splitlines() if not l.startswith("??")],
            "code_sha256": digest.hexdigest(), "code_files": len(files)}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--run-id", required=True)
    ap.add_argument("--select", nargs="+", required=True, help="task-id prefixes from configs/reproduction.yaml")
    ap.add_argument("--manifest", type=Path, default=REPO / "configs/reproduction.yaml")
    ap.add_argument("--wait-for", help="a Slurm job id that must end (in any state) before the first selected tasks start")
    args = ap.parse_args()
    manifest = yaml.safe_load(args.manifest.read_text())
    tasks = manifest["tasks"]
    chosen = [t for t in tasks if any(t == s or t.startswith(s + ".") for s in args.select)]
    if not chosen:
        raise SystemExit(f"no task matches {args.select}; known: {sorted(tasks)}")
    for t in chosen:
        missing = [n for n in tasks[t].get("needs", []) if n not in tasks]
        if missing:
            raise SystemExit(f"{t} needs unknown tasks {missing}")

    folder = HERE / "generated" / args.run_id
    folder.mkdir(parents=True, exist_ok=True)
    submit = ["#!/bin/bash",
              f"# Generated by torch/make_jobs.py for run {args.run_id}. Run on the cluster: bash torch/generated/{args.run_id}/submit.sh",
              "# Account, paths and the conda environment come from torch/cluster.sh (environment variables or torch/.env).",
              "set -euo pipefail",
              'source "$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)/cluster.sh"',
              f'export BM_RUN="$BM_SCRATCH/reproduction/{args.run_id}" BM_OUT="$BM_REPO/runs/{args.run_id}"',
              'mkdir -p "$BM_RUN/logs" "$BM_OUT"',
              'export BM_CODE="$BM_RUN/code_$(date +%Y%m%dT%H%M%S)"',
              'mkdir -p "$BM_CODE"',
              'cp -a "$BM_REPO/src" "$BM_REPO/scripts" "$BM_REPO/configs" "$BM_REPO/torch" "$BM_CODE/"',
              'find "$BM_CODE" -name __pycache__ -prune -exec rm -rf {} +',
              'echo "account: ${BM_ACCOUNT:-(Slurm default)}  scratch: $BM_SCRATCH  repo: $BM_REPO  env: $BM_CONDA_ENV  '
              'extra: ${BM_SBATCH_ARGS:-(none)}  gpu: ${BM_GPU_TYPE:-any} ${BM_GPU_SBATCH_ARGS:-}"',
              'echo "code snapshot: $BM_CODE"',
              "declare -A JOB",
              'submit() { local name=$1; shift; JOB[$name]=$(sbatch --parsable ${BM_ACCOUNT:+--account="$BM_ACCOUNT"} $BM_SBATCH_ARGS '
              '--output="$BM_RUN/logs/${name%.resume[0-9]*}_%A_%a.log" --export=ALL,BM_CODE="$BM_CODE" "$@"); '
              'echo -e "$name\\t${JOB[$name]}\\t$(date -Is)" | tee -a "$BM_RUN/jobs.tsv"; }',
              'after() { local kind=$1; shift; local ids=""; for n in "$@"; do [ -n "${JOB[$n]:-}" ] && ids="$ids:${JOB[$n]}"; done; '
              '[ -n "$ids" ] && echo "--dependency=$kind$ids"; return 0; }', ""]
    listing = {}
    for t in chosen:           # manifest order is dependency order
        task = tasks[t]
        lines = commands(t, task)
        (folder / f"{t}.tasks").write_text("\n".join(lines) + "\n")
        res = task["resources"]
        # a GPU task gets its --gres at submission, so the GPU model is a personal setting (BM_GPU_TYPE)
        gres = f"# GPU task: {res['gpu']} GPU, requested by submit.sh\n" if res.get("gpu") else ""
        gpu = (f' --gres="gpu:${{BM_GPU_TYPE:+$BM_GPU_TYPE:}}{res["gpu"]}" $BM_GPU_SBATCH_ARGS' if res.get("gpu") else "")
        throttle = f"%{res['throttle']}" if res.get("throttle") else ""
        env = "".join(f'export {k}="{v}"\n' for k, v in (task.get("env") or {}).items())
        cwd = "$BM_REPO" if task.get("cwd") == "repo" else "$BM_CODE"   # "repo": pytest tasks, which need tests/
        (folder / f"{t}.sbatch").write_text(SBATCH.format(
            job="bm_" + t.replace("gate.", "g.").replace("synergy.", "s.").replace("motion_v2.", "m.")[:28],
            cpus=res["cpus"], mem=res["mem"], time=res["time"], last=len(lines) - 1,
            throttle=throttle, task=t, gres=gres, env=env, cwd=cwd, run_id=args.run_id))
        needs = " ".join(task.get("needs", []))
        waits = f" --dependency=afterany:{args.wait_for}" if args.wait_for and not any(n in chosen for n in task.get("needs", [])) else ""
        call = f'submit {t} $(after afterok {needs}){waits}{gpu} "$BM_CODE/torch/generated/{args.run_id}/{t}.sbatch"'
        if task.get("done_when"):
            submit.append(f'if [ -e "{task["done_when"]}" ]; then echo "{t}: already done"; else {call}; fi')
        else:
            submit.append(call)
        previous = t
        for k in range(task.get("resubmit", 0)):   # each resubmission continues whatever the last one left unfinished
            name = f"{t}.resume{k + 1}"
            submit.append(f'submit {name} $(after afterany {previous}){gpu} "$BM_CODE/torch/generated/{args.run_id}/{t}.sbatch"')
            previous = name
        if task.get("resubmit"):   # tasks that need this one wait for its last resubmission
            submit.append(f'JOB[{t}]="${{JOB[{previous}]:-}}"')
        listing[t] = {"array_size": len(lines), "commands": lines, "needs": task.get("needs", []),
                      "resources": res, "resubmit": task.get("resubmit", 0)}
    submit += ["", 'echo "submitted: ${!JOB[@]}"']
    (folder / "submit.sh").write_text("\n".join(submit) + "\n")
    record = REPO / "runs" / args.run_id / "run.json"
    record.parent.mkdir(parents=True, exist_ok=True)
    previous = json.loads(record.read_text()) if record.exists() else {}
    history = previous.get("submissions", [])
    history.append({"generated": time.strftime("%Y-%m-%dT%H:%M:%S%z"), "selected": args.select, "tasks": listing,
                    "cluster_settings": "read on the cluster at submission (torch/cluster.sh); printed by submit.sh",
                    "manifest_sha256": hashlib.sha256(args.manifest.read_bytes()).hexdigest(), **code_state()})
    record.write_text(json.dumps({**previous, "run_id": args.run_id, "submissions": history}, indent=2) + "\n")
    total = sum(v["array_size"] for v in listing.values())
    print(f"{len(listing)} tasks, {total} array jobs -> {folder.relative_to(REPO)}/submit.sh")
    for t, v in listing.items():
        print(f"  {t:42s} x{v['array_size']:<3d} needs {v['needs'] or '-'}")


if __name__ == "__main__":
    sys.exit(main())
