"""Freeze the reference values that reruns are compared with.

    python scripts/aggregate_results/freeze_reference_values.py

Reads the published result files and the 11 Nov panel spec (read-only) and writes
configs/reference_values.json with every number copied by code, the path it came from and the
SHA256 of that file. The aggregator and the panel builder read only that file and a run
directory; they never open results/.
"""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GATE = "results/memory_baselines/gate_team/summary.json"
SYNERGY_RELEASED = "results/memory_baselines/synergy/released_scores.json"
SYNERGY_LITERATURE = "results/memory_baselines/synergy/summary.json"
MOTION_ONLINE = "docs/MOTION_V2_STEP3_4_RECOVERY1_REPORT_ZH.md"
MOTION_ARMS = "docs/MOTION_V2_3_1_RESUBMISSION_REPORT_ZH.md"
PANEL = "reports/memory_results_20261111/spec/spec.json"


def sha(path):
    return hashlib.sha256((ROOT / path).read_bytes()).hexdigest()


def gate():
    scores = json.loads((ROOT / GATE).read_text())["scores"]
    return {name: {"route_accuracy": v["route_accuracy"], "normalized_mse": v["normalized_mse"], "cue_kept": v["cue_kept"],
                   "route_accuracy_by_seed": v["route_accuracy_by_seed"]} for name, v in scores.items()}


def synergy():
    released = json.loads((ROOT / SYNERGY_RELEASED).read_text())["readers"]
    literature = json.loads((ROOT / SYNERGY_LITERATURE).read_text())["readers"]
    out = {}
    for reader in released:
        rows = {}
        for name, value in released[reader].items():
            if "S" in value:
                rows[name] = {t: {k: value[t][k] for k in ("needed_evidence_lost", "regret")} for t in "RDS"}
        for name in ("pafu_kv", "pafu_teacher_top2", "pacc", "fm_published", "fm_teacher_top2"):
            rows[name] = {t: {k: literature[reader][name][t][k] for k in ("needed_evidence_lost", "regret")} for t in "RDS"}
        check = released[reader]["deletion_path_check"]["max_abs_diff_from_released_cost"]
        out[reader] = {"policies": rows, "deletion_path_check_max_abs_diff": check}
    return out


def table(path, start, stop, cells_per_row):
    section = (ROOT / path).read_text().split(start, 1)[1].split(stop, 1)[0]
    rows = []
    for line in section.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) == cells_per_row and cells[1] in ("3", "6"):
            rows.append(cells)
    return rows


def motion():
    """Published Motion v2 tables, keyed like the evidence files (kind/method)."""
    def key(name):
        name = name.replace("**INIT**", "").strip()
        if name.startswith("参照/"):
            return "reference/" + name.split("/", 1)[1]
        if "/" in name:
            arch, label = name.split("/", 1)
            return f"student/{arch}_{label}"
        return "baseline/" + name

    out = {}
    for interval, start, stop in (("ordinary", "### 普通间隔（主要）", "### Long gap"),
                                  ("long_gap", "### Long gap（单独报告）", "## 7.")):
        rows = {}
        for cells in table(MOTION_ONLINE, start, stop, 5):
            entry = rows.setdefault(key(cells[0]), {"position_mse": {}, "feature_mse": {}})
            entry["success_rate_percent"] = float(cells[2].split()[0])
            entry["position_mse"][cells[1]] = float(cells[3].split()[0])
            entry["feature_mse"][cells[1]] = float(cells[4].split()[0])
        out[interval] = rows
    arms = {}
    for cells in table(MOTION_ARMS, "a 为 recent-only", "以下差值直接引用", 6):
        if cells[0] in "abcd" and cells[1] not in arms.get(cells[0], {}).get("position_mse", {}):
            entry = arms.setdefault(cells[0], {"position_mse": {}, "feature_mse": {}})
            entry["feature_mse"][cells[1]] = float(cells[2])
            entry["position_mse"][cells[1]] = float(cells[4])
    return {"online": out, "reference_arms": arms}


def panel():
    spec = json.loads((ROOT / PANEL).read_text())
    return {u["name"]: {"metric": u["figure"]["metric"], "decimals": u["figure"].get("decimals"),
                        "rows": u["figure"]["rows"], "values": u["figure"].get("values", {})} for u in spec["units"]}


def main():
    sources = [GATE, SYNERGY_RELEASED, SYNERGY_LITERATURE, MOTION_ONLINE, MOTION_ARMS, PANEL]
    reference = {"note": "generated by scripts/aggregate_results/freeze_reference_values.py; do not edit by hand",
                 "sources": {p: sha(p) for p in sources},
                 "gate": gate(), "synergy": synergy(), "motion_v2": motion(), "panel": panel()}
    out = ROOT / "configs/reference_values.json"
    out.write_text(json.dumps(reference, indent=1, ensure_ascii=False) + "\n")
    m = reference["motion_v2"]
    print(f"wrote {out.relative_to(ROOT)}: gate {len(reference['gate'])} policies, synergy "
          f"{ {r: len(v['policies']) for r, v in reference['synergy'].items()} }, motion "
          f"{ {k: len(v) for k, v in m['online'].items()} } + arms {sorted(m['reference_arms'])}, panel {list(reference['panel'])}")


if __name__ == "__main__":
    main()
